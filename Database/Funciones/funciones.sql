CREATE OR ALTER FUNCTION FN_CALCULAR_PROYECCION_GASTO_MENSUAL (
    P_ID_SUBCATEGORIA INTEGER,
    P_ID_PRESUPUESTO INTEGER,
    P_ANIO INTEGER,
    P_MES INTEGER
)
RETURNS DECIMAL(18,2)
AS
DECLARE VARIABLE EJECUTADO DECIMAL(18,2);
DECLARE VARIABLE PRIMER_DIA DATE;
DECLARE VARIABLE DIAS_MES INTEGER;
DECLARE VARIABLE DIAS_PASADOS INTEGER;
BEGIN
    EJECUTADO = FN_CALCULAR_MONTO_EJECUTADO(:P_ID_SUBCATEGORIA, :P_ID_PRESUPUESTO, :P_ANIO, :P_MES);

    PRIMER_DIA = DATEADD(MONTH, ((:P_ANIO - 2000) * 12) + :P_MES - 1, CAST('2000-01-01' AS DATE));
    DIAS_MES = EXTRACT(DAY FROM DATEADD(DAY, -1, DATEADD(MONTH, 1, PRIMER_DIA)));

    IF (:P_ANIO = EXTRACT(YEAR FROM CURRENT_DATE) AND :P_MES = EXTRACT(MONTH FROM CURRENT_DATE)) THEN
        DIAS_PASADOS = EXTRACT(DAY FROM CURRENT_DATE);
    ELSE
        DIAS_PASADOS = DIAS_MES;

    IF (DIAS_PASADOS = 0) THEN
        RETURN 0;

    RETURN (EJECUTADO / DIAS_PASADOS) * DIAS_MES;
END^



CREATE OR ALTER FUNCTION FN_OBTENER_PROMEDIO_GASTO_SUBCATEGORIA (
    P_ID_USUARIO INTEGER,
    P_ID_SUBCATEGORIA INTEGER,
    P_CANTIDAD_MESES INTEGER
)
RETURNS DECIMAL(18,2)
AS
DECLARE VARIABLE TOTAL DECIMAL(18,2);
DECLARE VARIABLE PERIODO_ACTUAL INTEGER;
DECLARE VARIABLE PERIODO_DESDE INTEGER;
BEGIN
    IF (P_CANTIDAD_MESES IS NULL OR P_CANTIDAD_MESES <= 0) THEN
        RETURN 0;

    PERIODO_ACTUAL = (EXTRACT(YEAR FROM CURRENT_DATE) * 12) + EXTRACT(MONTH FROM CURRENT_DATE);
    PERIODO_DESDE = PERIODO_ACTUAL - P_CANTIDAD_MESES;

    SELECT COALESCE(SUM(MONTO), 0)
    FROM TRANSACCION
    WHERE ID_USUARIO = :P_ID_USUARIO
      AND ID_SUBCATEGORIA = :P_ID_SUBCATEGORIA
      AND ((ANIO * 12) + MES) > :PERIODO_DESDE
      AND ((ANIO * 12) + MES) <= :PERIODO_ACTUAL
    INTO :TOTAL;

    RETURN TOTAL / P_CANTIDAD_MESES;
END^

