CREATE OR ALTER FUNCTION FN_DIAS_HASTA_VENCIMIENTO (P_ID_OBLIGACION INTEGER)
RETURNS INTEGER
AS
DECLARE VARIABLE DIA INTEGER;
DECLARE VARIABLE PRIMER_DIA DATE;
DECLARE VARIABLE ULTIMO_DIA DATE;
DECLARE VARIABLE DIA_REAL INTEGER;
DECLARE VARIABLE FECHA_VENCE DATE;
BEGIN
    SELECT DIA_VENCIMIENTO
    FROM OBLIGACION_FIJA
    WHERE ID_OBLIGACION = :P_ID_OBLIGACION
    INTO :DIA;

    IF (DIA IS NULL) THEN
        RETURN NULL;

    PRIMER_DIA = DATEADD(DAY, -(EXTRACT(DAY FROM CURRENT_DATE) - 1), CURRENT_DATE);
    ULTIMO_DIA = DATEADD(DAY, -1, DATEADD(MONTH, 1, PRIMER_DIA));

    DIA_REAL = DIA;
    IF (DIA_REAL > EXTRACT(DAY FROM ULTIMO_DIA)) THEN
        DIA_REAL = EXTRACT(DAY FROM ULTIMO_DIA);

    FECHA_VENCE = DATEADD(DAY, DIA_REAL - 1, PRIMER_DIA);

    RETURN DATEDIFF(DAY, CURRENT_DATE, FECHA_VENCE);
END^



CREATE OR ALTER FUNCTION FN_VALIDAR_VIGENCIA_PRESUPUESTO (
    P_FECHA DATE,
    P_ID_PRESUPUESTO INTEGER
)
RETURNS BOOLEAN
AS
DECLARE VARIABLE INICIO INTEGER;
DECLARE VARIABLE FIN INTEGER;
DECLARE VARIABLE PERIODO INTEGER;
BEGIN
    SELECT (ANIO_INICIO * 12) + MES_INICIO, (ANIO_FIN * 12) + MES_FIN
    FROM PRESUPUESTO
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
    INTO :INICIO, :FIN;

    IF (INICIO IS NULL) THEN
        RETURN FALSE;

    PERIODO = (EXTRACT(YEAR FROM :P_FECHA) * 12) + EXTRACT(MONTH FROM :P_FECHA);

    IF (PERIODO >= INICIO AND PERIODO <= FIN) THEN
        RETURN TRUE;
    ELSE
        RETURN FALSE;
END^



