CREATE OR ALTER FUNCTION FN_CALCULAR_MONTO_EJECUTADO (
    P_ID_SUBCATEGORIA INTEGER,
    P_ID_PRESUPUESTO INTEGER,
    P_ANIO INTEGER,
    P_MES INTEGER
)
RETURNS DECIMAL(18,2)
AS
DECLARE VARIABLE TOTAL DECIMAL(18,2);
BEGIN
    SELECT COALESCE(SUM(MONTO), 0)
    FROM TRANSACCION
    WHERE ID_SUBCATEGORIA = :P_ID_SUBCATEGORIA
      AND ID_PRESUPUESTO = :P_ID_PRESUPUESTO
      AND ANIO = :P_ANIO
      AND MES = :P_MES
    INTO :TOTAL;

    RETURN TOTAL;
END^ 



CREATE OR ALTER FUNCTION FN_CALCULAR_PORCENTAJE_EJECUTADO (
    P_ID_SUBCATEGORIA INTEGER,
    P_ID_PRESUPUESTO INTEGER,
    P_ANIO INTEGER,
    P_MES INTEGER
)
RETURNS DECIMAL(18,2)
AS
DECLARE VARIABLE PRESUPUESTADO DECIMAL(18,2);
DECLARE VARIABLE EJECUTADO DECIMAL(18,2);
BEGIN
    SELECT MONTO_MENSUAL_ASIGNADO
    FROM PRESUPUESTO_DETALLE
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
      AND ID_SUBCATEGORIA = :P_ID_SUBCATEGORIA
    INTO :PRESUPUESTADO;

    IF (PRESUPUESTADO IS NULL OR PRESUPUESTADO = 0) THEN
        RETURN 0;

    EJECUTADO = FN_CALCULAR_MONTO_EJECUTADO(:P_ID_SUBCATEGORIA, :P_ID_PRESUPUESTO, :P_ANIO, :P_MES);

    RETURN (EJECUTADO / PRESUPUESTADO) * 100;
END^



CREATE OR ALTER FUNCTION FN_OBTENER_BALANCE_SUBCATEGORIA (
    P_ID_PRESUPUESTO INTEGER,
    P_ID_SUBCATEGORIA INTEGER,
    P_ANIO INTEGER,
    P_MES INTEGER
)
RETURNS DECIMAL(18,2)
AS
DECLARE VARIABLE PRESUPUESTADO DECIMAL(18,2);
DECLARE VARIABLE EJECUTADO DECIMAL(18,2);
BEGIN
    SELECT MONTO_MENSUAL_ASIGNADO
    FROM PRESUPUESTO_DETALLE
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
      AND ID_SUBCATEGORIA = :P_ID_SUBCATEGORIA
    INTO :PRESUPUESTADO;

    IF (PRESUPUESTADO IS NULL) THEN
        PRESUPUESTADO = 0;

    EJECUTADO = FN_CALCULAR_MONTO_EJECUTADO(:P_ID_SUBCATEGORIA, :P_ID_PRESUPUESTO, :P_ANIO, :P_MES);

    RETURN PRESUPUESTADO - EJECUTADO;
END^



