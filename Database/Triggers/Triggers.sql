

CREATE EXCEPTION EX_TIPO_TRANSACCION
'El tipo de la transaccion no coincide con el tipo de su categoria';

CREATE EXCEPTION EX_FUERA_VIGENCIA
'El anio y mes de la transaccion estan fuera de la vigencia del presupuesto';


SET TERM ^ ;



CREATE TRIGGER TRG_SUBCATEGORIA_DEFECTO FOR CATEGORIA
AFTER INSERT
AS
BEGIN
    INSERT INTO SUBCATEGORIA (ID_CATEGORIA, NOMBRE_SUBCATEGORIA, ACTIVA, ES_DEFECTO, CREADO_EN)
    VALUES (NEW.ID_CATEGORIA, 'General', TRUE, TRUE, CURRENT_TIMESTAMP);
END^



CREATE TRIGGER TRG_USUARIO_AUDITORIA FOR USUARIO
BEFORE INSERT OR UPDATE
AS
BEGIN
    IF (INSERTING) THEN NEW.CREADO_EN = CURRENT_TIMESTAMP;
    IF (UPDATING) THEN NEW.MODIFICADO_EN = CURRENT_TIMESTAMP;
END^



