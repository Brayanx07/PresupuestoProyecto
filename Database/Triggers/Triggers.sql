CREATE TRIGGER TRG_TRANSACCION_VALIDA_TIPO FOR TRANSACCION
BEFORE INSERT OR UPDATE
AS
DECLARE VARIABLE TIPO_CAT VARCHAR(20);
BEGIN
    SELECT C.TIPO_CATEGORIA
    FROM SUBCATEGORIA S
    INNER JOIN CATEGORIA C ON C.ID_CATEGORIA = S.ID_CATEGORIA
    WHERE S.ID_SUBCATEGORIA = NEW.ID_SUBCATEGORIA
    INTO :TIPO_CAT;

    IF (NEW.TIPO_TRANSACCION <> TIPO_CAT) THEN
        EXCEPTION EX_TIPO_TRANSACCION;
END^



CREATE TRIGGER TRG_TRANSACCION_VALIDA_PERIODO FOR TRANSACCION
BEFORE INSERT OR UPDATE
AS
DECLARE VARIABLE INICIO INTEGER;
DECLARE VARIABLE FIN INTEGER;
BEGIN
    SELECT (ANIO_INICIO * 12) + MES_INICIO, (ANIO_FIN * 12) + MES_FIN
    FROM PRESUPUESTO
    WHERE ID_PRESUPUESTO = NEW.ID_PRESUPUESTO
    INTO :INICIO, :FIN;

    IF ((NEW.ANIO * 12) + NEW.MES < INICIO) THEN
        EXCEPTION EX_FUERA_VIGENCIA;

    IF ((NEW.ANIO * 12) + NEW.MES > FIN) THEN
        EXCEPTION EX_FUERA_VIGENCIA;
END^

SET TERM ; ^





