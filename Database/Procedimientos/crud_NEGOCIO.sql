CREATE OR ALTER PROCEDURE SP_OBTENER_RESUMEN_CATEGORIA_MES (
    P_ID_CATEGORIA INTEGER,
    P_ID_PRESUPUESTO INTEGER,
    P_ANIO INTEGER,
    P_MES INTEGER
)
RETURNS (
    MONTO_PRESUPUESTADO DECIMAL(18,2),
    MONTO_EJECUTADO DECIMAL(18,2),
    PORCENTAJE DECIMAL(18,2)
)
AS
BEGIN
    MONTO_PRESUPUESTADO = FN_OBTENER_TOTAL_CATEGORIA_MES(:P_ID_CATEGORIA, :P_ID_PRESUPUESTO, :P_ANIO, :P_MES);
    MONTO_EJECUTADO = FN_OBTENER_TOTAL_EJECUTADO_CATEGORIA_MES(:P_ID_CATEGORIA, :P_ID_PRESUPUESTO, :P_ANIO, :P_MES);

    IF (MONTO_PRESUPUESTADO = 0) THEN
        PORCENTAJE = 0;
    ELSE
        PORCENTAJE = (MONTO_EJECUTADO / MONTO_PRESUPUESTADO) * 100;

    SUSPEND;
END^



CREATE OR ALTER PROCEDURE SP_CERRAR_PRESUPUESTO (
    P_ID_PRESUPUESTO INTEGER,
    P_MODIFICADO_POR INTEGER
)
RETURNS (
    TOTAL_PRESUPUESTADO DECIMAL(18,2),
    TOTAL_EJECUTADO DECIMAL(18,2),
    PORCENTAJE DECIMAL(18,2)
)
AS
DECLARE VARIABLE FIN INTEGER;
DECLARE VARIABLE ACTUAL INTEGER;
DECLARE VARIABLE MESES INTEGER;
BEGIN
    SELECT (ANIO_FIN * 12) + MES_FIN,
           ((ANIO_FIN * 12) + MES_FIN) - ((ANIO_INICIO * 12) + MES_INICIO) + 1
    FROM PRESUPUESTO
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
    INTO :FIN, :MESES;

    ACTUAL = (EXTRACT(YEAR FROM CURRENT_DATE) * 12) + EXTRACT(MONTH FROM CURRENT_DATE);

    IF (FIN >= ACTUAL) THEN
        EXCEPTION EX_PRESUPUESTO_VIGENTE;

    SELECT COALESCE(SUM(MONTO_MENSUAL_ASIGNADO), 0) * :MESES
    FROM PRESUPUESTO_DETALLE
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
    INTO :TOTAL_PRESUPUESTADO;

    SELECT COALESCE(SUM(MONTO), 0)
    FROM TRANSACCION
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO
    INTO :TOTAL_EJECUTADO;

    IF (TOTAL_PRESUPUESTADO = 0) THEN
        PORCENTAJE = 0;
    ELSE
        PORCENTAJE = (TOTAL_EJECUTADO / TOTAL_PRESUPUESTADO) * 100;

    UPDATE PRESUPUESTO
    SET ESTADO_PRESUPUESTO = 'cerrado',
        MODIFICADO_POR = :P_MODIFICADO_POR
    WHERE ID_PRESUPUESTO = :P_ID_PRESUPUESTO;

    SUSPEND;
END^

SET TERM ; ^

